#!/usr/bin/env python3
"""
index_solutions.py
Scans all solutions across DSA pattern folders, collects problem metadata,
and generates/updates PROBLEM_INDEX.md with verified links and categories.
"""

import os
import re
import json

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

PATTERN_DIRS = [
    "Arrays-and-Hashing",
    "Backtracking",
    "Binary-Search",
    "Database",
    "Dynamic-Programming",
    "Graphs",
    "Greedy-Algorithms",
    "Heaps-and-Priority-Queues",
    "Intervals",
    "JavaScript",
    "Linked-Lists",
    "Math-and-Bit-Manipulation",
    "Shell",
    "Stacks-and-Queues",
    "Strings",
    "Trees-and-Binary-Search-Trees",
    "Two-Pointers-and-Sliding-Window",
]

LANGUAGE_MAP = {
    ".py": "Python",
    ".cpp": "C++",
    ".sql": "SQL",
    ".js": "JavaScript",
    ".txt": "Shell / Regex",
}

def parse_filename(filename):
    """Extracts problem number, raw title, and extension."""
    m = re.match(r"^(\d+)[\-_](.+)\.([a-zA-Z0-9]+)$", filename)
    if m:
        return int(m.group(1)), m.group(2), "." + m.group(3).lower()
    base, ext = os.path.splitext(filename)
    return None, base, ext.lower()

def prettify_title(raw_title):
    """Converts snake_case or camelCase into a readable title."""
    s = raw_title.replace("_", " ")
    # Insert space before camel case caps if needed
    s = re.sub(r'([a-z])([A-Z])', r'\1 \2', s)
    return s.strip()

def scan_solutions(repo_root=REPO_ROOT):
    solutions = []
    for pattern in PATTERN_DIRS:
        folder_path = os.path.join(repo_root, pattern)
        if not os.path.isdir(folder_path):
            continue
        for fname in sorted(os.listdir(folder_path)):
            fpath = os.path.join(folder_path, fname)
            if not os.path.isfile(fpath) or fname.startswith("."):
                continue
            
            pnum, raw_title, ext = parse_filename(fname)
            rel_link = f"{pattern}/{fname}".replace("\\", "/")
            
            # Check if difficulty is stated in file comments
            difficulty = "Unspecified"
            try:
                with open(fpath, "r", encoding="utf-8", errors="replace") as f:
                    content = f.read(500)
                    m_diff = re.search(r'\b(Easy|Medium|Hard)\b', content, re.IGNORECASE)
                    if m_diff:
                        difficulty = m_diff.group(1).capitalize()
            except Exception:
                pass

            lang = LANGUAGE_MAP.get(ext, ext)
            # Special check for SQL inside .py
            if pattern == "Database" and ext == ".py":
                lang = "SQL (Python file)"

            solutions.append({
                "problem_number": pnum,
                "raw_title": raw_title,
                "display_title": prettify_title(raw_title),
                "filename": fname,
                "category": pattern,
                "extension": ext,
                "language": lang,
                "difficulty": difficulty,
                "rel_path": rel_link,
                "full_path": fpath,
            })

    solutions.sort(key=lambda s: (s["problem_number"] if s["problem_number"] is not None else 999999, s["filename"]))
    return solutions

def generate_index_markdown(solutions, output_file=None):
    if output_file is None:
        output_file = os.path.join(REPO_ROOT, "PROBLEM_INDEX.md")

    total_solutions = len(solutions)
    unique_ids = len({s["problem_number"] for s in solutions if s["problem_number"] is not None})
    no_ids = len([s for s in solutions if s["problem_number"] is None])
    total_unique = unique_ids + no_ids

    lines = [
        "# Complete Problem Index",
        "",
        f"> **Total Solutions:** {total_solutions} | **Unique Problems:** {total_unique} | **Indexed Categories:** {len(PATTERN_DIRS)}",
        "",
        "This index is automatically generated and synchronized with repository files by `scripts/index_solutions.py`.",
        "",
        "| # | Problem Title | Pattern Category | Language | Verified Difficulty | Solution Link |",
        "|---|---------------|------------------|----------|---------------------|---------------|",
    ]

    for s in solutions:
        pnum_str = f"#{s['problem_number']}" if s['problem_number'] is not None else "N/A"
        clean_title = s['display_title']
        cat = s['category']
        lang = s['language']
        diff = s['difficulty']
        link = f"[{s['filename']}]({s['rel_path']})"
        lines.append(f"| {pnum_str} | {clean_title} | `{cat}` | {lang} | {diff} | {link} |")

    lines.append("")
    lines.append("---")
    lines.append("*Generated by scripts/index_solutions.py*")
    lines.append("")

    content = "\n".join(lines)
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Problem index successfully written to {output_file} ({total_solutions} solutions indexed).")

if __name__ == "__main__":
    sols = scan_solutions()
    generate_index_markdown(sols)

